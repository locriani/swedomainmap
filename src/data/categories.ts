// Dedupe roles per item so role lists composed via spread (e.g. ...WEB plus 'fullstack')
// don't double-count if a future metric counts list length. The id is auto-derived
// from the label via `slugify`; uniqueness is enforced by a data test. If two
// labels collide after slugification (e.g. "C" and "C++" both → "c"), pass an
// explicit id via `iId` to disambiguate.
const i = (label: string, ...roles: RoleId[]): Item => ({
  id: slugify(label),
  label,
  roles: Array.from(new Set(roles)),
});

const iId = (id: string, label: string, ...roles: RoleId[]): Item => ({
  id,
  label,
  roles: Array.from(new Set(roles)),
});

/**
 * Like `i()` but with per-role seniority annotations. Use for items where some
 * roles are expected to know it earlier (Jr) or later (Sr/Staff) than the
 * default Mid baseline. Only annotate roles whose expectation diverges from
 * Mid — leaving them unset preserves the calibrated default.
 *
 *   iLv('SwiftUI', { ios: 'jr' }, 'ios', 'xr', 'a11y')
 *   iLv('Kubernetes (...)', { devops: 'mid', backend: 'sr' }, 'devops', 'backend', ...)
 *
 * The data tests assert that every key in `levels` is also present in `roles`.
 */
const iLv = (
  label: string,
  levels: Partial<Record<RoleId, Level>>,
  ...roles: RoleId[]
): Item => ({
  id: slugify(label),
  label,
  roles: Array.from(new Set(roles)),
  levels,
});

